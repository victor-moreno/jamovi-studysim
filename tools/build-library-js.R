# Embed the built-in library in the options panel: writes jamovi/js/builtin.js
# from inst/library (run before building; tools/smoke.R checks it is current).
pkgload::load_all(".", quiet = TRUE)
lib <- read_library_dir("inst/library")
p <- check_library(lib)
if (any(p$level == "error")) stop(paste(p$scenario, p$where, p$message, collapse = "\n"))
# the library plus the three name/level dictionaries (inst/library/i18n)
i18n <- lapply(stats::setNames(LANGS, LANGS), function(l) read_yaml_file(file.path("inst/library/i18n", paste0(l, ".yaml"))))
obj <- jsonlite::toJSON(list(variables = lib$dictionary, scenarios = lib$scenarios, i18n = i18n),
                        auto_unbox = TRUE, null = "null", digits = NA)
js <- c("// GENERATED by tools/build-library-js.R from inst/library -- do not edit",
        paste0("module.exports = ", obj, ";"))
writeLines(js, "jamovi/js/builtin.js", useBytes = TRUE)
cat("wrote jamovi/js/builtin.js:", length(lib$scenarios), "scenarios,", file.size("jamovi/js/builtin.js"), "bytes\n")
